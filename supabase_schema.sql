create table if not exists public.users (
    id bigint generated by default as identity primary key,
    name text not null,
    email text not null unique,
    password_hash text not null,
    role text not null check (role in ('user', 'admin')),
    farm_name text,
    status text not null default 'active' check (status in ('active', 'inactive', 'suspended')),
    created_at timestamptz not null default now()
);

create index if not exists users_status_idx
    on public.users (status);

create table if not exists public.project_history (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    project text not null,
    action text not null,
    upload_filename text,
    upload_content_type text,
    upload_storage_path text,
    upload_public_url text,
    request_payload jsonb not null default '{}'::jsonb,
    response_payload jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists project_history_user_created_idx
    on public.project_history (user_id, created_at desc);

create index if not exists project_history_project_idx
    on public.project_history (project);

create table if not exists public.auth_events (
    id bigint generated by default as identity primary key,
    user_id bigint references public.users(id) on delete set null,
    email text,
    event_type text not null check (event_type in ('register', 'login', 'logout')),
    success boolean not null default true,
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists auth_events_user_created_idx
    on public.auth_events (user_id, created_at desc);

create index if not exists auth_events_email_created_idx
    on public.auth_events (email, created_at desc);

create table if not exists public.farms (
    id bigint generated by default as identity primary key,
    farm_name text not null,
    location text not null,
    size numeric(10,2) not null default 0,
    fields integer not null default 1,
    status text not null default 'active' check (status in ('active', 'inactive', 'maintenance')),
    created_at timestamptz not null default now()
);

create index if not exists farms_status_idx
    on public.farms (status);

create table if not exists public.crops (
    id bigint generated by default as identity primary key,
    crop_name text not null,
    varieties text,
    maturity_period text,
    growth_stage text,
    supported_disease_category text,
    status text default 'active',
    created_at timestamptz not null default now()
);

create index if not exists crops_name_idx
    on public.crops (crop_name);

create table if not exists public.irrigation (
    id bigint generated by default as identity primary key,
    user_id bigint references public.users(id) on delete set null,
    farm_id bigint references public.farms(id) on delete set null,
    farmer_name text not null,
    farm_name text not null,
    crop_name text not null,
    variety text,
    location text,
    stage text,
    soil_type text,
    moisture_percent numeric(5,2) default 0,
    temperature_c numeric(5,2) default 0,
    humidity_percent numeric(5,2) default 0,
    rain_3d_mm numeric(5,2) default 0,
    last_watered date,
    status text not null default 'adequate' check (status in ('adequate', 'low soil moisture', 'excess moisture', 'monitoring required')),
    recommendation text,
    updated_at timestamptz not null default now()
);

create index if not exists irrigation_farm_idx
    on public.irrigation (farm_name);

create index if not exists irrigation_status_idx
    on public.irrigation (status);

create table if not exists public.harvest_submissions (
    id bigint generated by default as identity primary key,
    user_id bigint references public.users(id) on delete set null,
    submitted_by text not null,
    crop text not null,
    region text not null,
    planting_date date not null,
    expected_harvest_start date,
    expected_harvest_end date,
    calendar_code text,
    model_window jsonb not null default '{}'::jsonb,
    notes text,
    status text not null default 'submitted' check (status in ('submitted', 'reviewed', 'approved')),
    created_at timestamptz not null default now()
);

create index if not exists harvest_submissions_user_idx
    on public.harvest_submissions (user_id, created_at desc);

create index if not exists harvest_submissions_crop_idx
    on public.harvest_submissions (crop, region);

create table if not exists public.audit_logs (
    id bigint generated by default as identity primary key,
    user_name text not null,
    activity text not null,
    affected_record text not null,
    activity_date date not null default current_date,
    activity_time time not null default current_time,
    status text not null default 'success' check (status in ('success', 'failed')),
    created_at timestamptz not null default now()
);

create index if not exists audit_logs_created_idx
    on public.audit_logs (created_at desc);

create index if not exists audit_logs_status_idx
    on public.audit_logs (status);

